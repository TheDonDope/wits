#!/usr/bin/env bash
#
# Re-records the GIFs in assets/ from the *.tape files.
#
#   ./render-vhs-tapes.sh                     every tape
#   ./render-vhs-tapes.sh wits-bundle.tape    just the ones named
#
# One tape at a time, never in parallel: each render starts a Chromium, and the
# machine this is developed on has been OOM-killed by renders side by side.
# Every finished GIF is on disk before the next tape starts, so a crash loses
# at most one. The tapes run ./bin/wits, so it is rebuilt first — a stale
# binary would record yesterday's screens. ./doctor.sh says what vhs needs.

set -euo pipefail
cd "$(dirname "$0")"

if [ "$#" -gt 0 ]; then
	tapes=("$@")
else
	tapes=(*.tape)
fi

make build >/dev/null
# shellcheck disable=SC1090 # the exports are generated by doctor.sh
source <(./doctor.sh env)

total=${#tapes[@]}
for i in "${!tapes[@]}"; do
	tape="${tapes[i]}"
	out="$(sed -n 's/^Output //p' "$tape" | head -1)"
	before="$(stat -c %Y "$out" 2>/dev/null || echo 0)"
	gum style --bold "Rendering $((i + 1))/$total: $tape → $out"
	gum spin --title "Rendering..." -- vhs "$tape" || true
	# The tapes seed throwaway repositories under /tmp; none is worth keeping.
	rm -rf /tmp/wits-bun /tmp/wits-copy /tmp/wits-rec /tmp/wits-tour /tmp/wits-cli /tmp/wits-imp
	# gum spin swallows vhs's output, so success is judged by the file itself.
	if [ ! -s "$out" ] || [ "$(stat -c %Y "$out")" -le "$before" ]; then
		gum style --foreground 196 --bold "No fresh $out — vhs failed; run it bare to see why: vhs $tape"
		exit 1
	fi
	ls -l "$out"
done

gum style --foreground 40 --bold "Rendered $total tape(s)"
